/**
 * Generate VietQR URL for bank transfer
 * @param bankCode - Bank BIN code (6 digits) or short code
 * @param accountNumber - Bank account number
 * @param accountName - Account holder name
 * @param amount - Transfer amount (optional)
 * @param description - Transfer description (optional)
 */
export function generateVietQRUrl(params: {
  bankCode: string;
  accountNumber: string;
  accountName: string;
  amount?: number;
  description?: string;
}): string {
  const { bankCode, accountNumber, accountName, amount, description } = params;

  // VietQR API endpoint - format: https://img.vietqr.io/image/{bankCode}-{accountNumber}-{template}.png
  const baseUrl = "https://img.vietqr.io/image";
  const cleanAccountNumber = accountNumber.replace(/\s/g, '');

  // Build URL with path parameters
  const url = `${baseUrl}/${bankCode}-${cleanAccountNumber}-qr_only.png`;

  // Build query parameters
  const queryParams = new URLSearchParams({
    amount: amount?.toString() || '',
    addInfo: encodeURIComponent(description || ''),
    accountName: encodeURIComponent(accountName),
  });

  return `${url}?${queryParams.toString()}`;
}

/**
 * Generate VietQR data for QR code generation
 * Used for client-side QR code generation
 */
export function generateVietQRData(params: {
  bankCode: string;
  accountNumber: string;
  accountName: string;
  amount?: number;
  description?: string;
}): string {
  const { bankCode, accountNumber, accountName, amount, description } = params;

  // Format: 00{BankID}{AccountNumber}{Amount}{Description}
  // This is a simplified version - full VietQR format is more complex
  const bankId = bankCode.padEnd(10, ' ').slice(0, 10);
  const accNo = accountNumber.replace(/\s/g, '').padEnd(20, ' ');
  const amt = amount ? Math.round(amount).toString().padStart(12, '0') : '0'.repeat(12);
  const desc = (description || '').padEnd(50, ' ').slice(0, 50);

  // VietQR merchant account info format (simplified)
  return `0002${bankId}${accNo}${amt}${desc}`;
}

/**
 * Check if bank info is complete for QR generation
 */
export function isBankInfoComplete(bank: {
  bankName?: string | null;
  bankAccountNumber?: string | null;
  bankAccountName?: string | null;
}): boolean {
  return !!(bank.bankName && bank.bankAccountNumber && bank.bankAccountName);
}
